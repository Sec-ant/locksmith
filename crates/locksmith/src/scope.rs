use std::collections::{BTreeMap, BTreeSet, HashMap, VecDeque};

use serde_json::{Map, json};

use crate::{Lockfile, LockfileError, Value, graft, graph, manifest};

/// Before/after package.json values supplied by the caller. `None` denotes
/// addition/deletion. Include unchanged local dependency manifests when their
/// candidate importer changes: peer declarations are not stored in importers.
#[derive(Debug, Clone, Copy)]
pub struct ManifestChange<'a> {
    pub importer: &'a str,
    pub before: Option<&'a Value>,
    pub after: Option<&'a Value>,
}

const METADATA: [&str; 15] = [
    "peerDependencies",
    "peerDependenciesMeta",
    "dependenciesMeta",
    "name",
    "version",
    "bin",
    "engines",
    "os",
    "cpu",
    "libc",
    "bundledDependencies",
    "bundleDependencies",
    "publishConfig",
    "type",
    "exports",
];

/// Converge a pnpm-generated candidate to package.json changes under unchanged
/// workspace configuration. Manifest declarations must match the corresponding
/// lockfile. Unchanged direct dependencies retain their baseline resolutions;
/// changed declarations, local workspace dependencies and affected peer contexts
/// use the candidate graph. Shared incompatible records produce conflicts.
///
/// The caller supplies all manifest changes and a candidate generated by pnpm.
/// The library does not resolve versions or execute pnpm hooks. Workspace-wide
/// changes (catalogs, overrides, patches, settings) use the explicit graft policy.
pub fn converge(
    baseline: &Lockfile,
    candidate: &Lockfile,
    changes: &[ManifestChange<'_>],
) -> Result<Lockfile, LockfileError> {
    let base = baseline.project().ok_or_else(|| {
        LockfileError::InvalidDocument("missing baseline project document".into())
    })?;
    let donor = candidate.project().ok_or_else(|| {
        LockfileError::InvalidDocument("missing candidate project document".into())
    })?;
    let mut changed = BTreeMap::new();
    let mut metadata_importers = BTreeSet::new();
    let mut providers = BTreeSet::new();
    let mut seen = BTreeSet::new();
    let mut manifests = BTreeMap::new();
    for change in changes {
        if !seen.insert(change.importer) || (change.before.is_none() && change.after.is_none()) {
            return Err(LockfileError::InvalidManifest(change.importer.into()));
        }
        for value in [change.before, change.after].into_iter().flatten() {
            if !value.is_object() {
                return Err(LockfileError::InvalidManifest(change.importer.into()));
            }
        }
        for field in ["pnpm", "packageManager", "devEngines"] {
            if get(change.before, field) != get(change.after, field) {
                return Err(LockfileError::GlobalConfigurationChanged {
                    importer: change.importer.into(),
                    field: field.into(),
                });
            }
        }
        manifest::check(base, change.importer, change.before, "baseline")?;
        manifests.insert(change.importer, change);
        let metadata = METADATA
            .iter()
            .any(|key| get(change.before, key) != get(change.after, key))
            || get(change.before, "scripts").and_then(|v| v.get("prepare"))
                != get(change.after, "scripts").and_then(|v| v.get("prepare"));
        let declarations = manifest::GROUPS
            .iter()
            .any(|key| get(change.before, key) != get(change.after, key));
        if change.before.is_some() && change.after.is_some() && !metadata && !declarations {
            continue;
        }
        manifest::check(donor, change.importer, change.after, "candidate")?;
        if metadata || change.before.is_none() {
            metadata_importers.insert(change.importer);
        }
        for field in manifest::GROUPS.into_iter().chain(["peerDependencies"]) {
            for m in [change.before, change.after].into_iter().flatten() {
                for name in m
                    .get(field)
                    .and_then(Value::as_object)
                    .into_iter()
                    .flatten()
                    .map(|(k, _)| k)
                {
                    if get(change.before, field).and_then(|v| v.get(name))
                        != get(change.after, field).and_then(|v| v.get(name))
                    {
                        providers.insert(name.clone());
                        for doc in [base, donor] {
                            if let Some(reference) = doc
                                .get("importers")
                                .and_then(|v| v.get(change.importer))
                                .and_then(|v| v.get(field))
                                .and_then(|v| v.get(name))
                                .and_then(|v| v.get("version"))
                                .and_then(Value::as_str)
                            {
                                let key = graph::snapshot_key(
                                    name,
                                    reference,
                                    graph::section(doc, "snapshots"),
                                );
                                if let Some((actual, _)) = graph::package_key(&key).rsplit_once('@')
                                {
                                    providers.insert(actual.into());
                                }
                            }
                        }
                    }
                }
            }
        }
        for m in [change.before, change.after].into_iter().flatten() {
            if let Some(name) = m.get("name").and_then(Value::as_str) {
                providers.insert(name.into());
            }
        }
        changed.insert(change.importer, change);
    }
    if changed.is_empty() {
        return Ok(baseline.clone());
    }
    baseline.validate()?;

    // Propagate local package changes through workspace consumers, including
    // injected/file packages. This changes edge provenance, not entire importers.
    let mut reverse: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut forward: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for document in [base, donor] {
        for (id, record) in graph::section(document, "importers").into_iter().flatten() {
            for group in manifest::GROUPS {
                for (name, dep) in record
                    .get(group)
                    .and_then(Value::as_object)
                    .into_iter()
                    .flatten()
                {
                    if let Some(target) = local_target(document, id, name, dep) {
                        reverse
                            .entry(target.clone())
                            .or_default()
                            .insert(id.clone());
                        forward.entry(id.clone()).or_default().insert(target);
                    }
                }
            }
        }
    }
    let mut affected: BTreeSet<String> = changed.keys().map(|s| (*s).into()).collect();
    let mut queue: VecDeque<_> = affected.iter().cloned().collect();
    let mut descendants = affected.clone();
    while let Some(parent) = queue.pop_front() {
        for target in forward.get(&parent).into_iter().flatten() {
            if !descendants.insert(target.clone()) {
                continue;
            }
            queue.push_back(target.clone());
            let old = base.get("importers").and_then(|v| v.get(target));
            let new = donor.get("importers").and_then(|v| v.get(target));
            if old != new {
                let context = manifests.get(target.as_str()).ok_or_else(|| {
                    manifest::mismatch(
                        target,
                        "candidate",
                        "include before/after manifests for this affected local dependency",
                    )
                })?;
                manifest::check(donor, target, context.after, "candidate")?;
                affected.insert(target.clone());
            }
        }
    }
    let mut queue: VecDeque<_> = affected.iter().cloned().collect();
    while let Some(target) = queue.pop_front() {
        for parent in reverse.get(&target).into_iter().flatten() {
            if affected.insert(parent.clone()) {
                queue.push_back(parent.clone());
            }
        }
    }
    let peer_base = affected_snapshots(base, &providers, &affected);
    let peer_donor = affected_snapshots(donor, &providers, &affected);
    let mut output = base.get("importers").cloned().unwrap_or_else(|| json!({}));
    for (id, change) in &changed {
        if change.after.is_none() {
            output.as_object_mut().unwrap().remove(*id);
        } else if change.before.is_none() {
            output[*id] = donor["importers"][*id].clone();
        }
    }
    let mut retained = Map::new();
    let mut adopted = Map::new();
    for (id, record) in output.as_object_mut().expect("importer map") {
        let old = base.get("importers").and_then(|v| v.get(id));
        let new = donor.get("importers").and_then(|v| v.get(id));
        let mut old_edges = Map::new();
        let mut new_edges = Map::new();
        let mut merged = if metadata_importers.contains(id.as_str()) {
            new.expect("manifest-checked candidate").clone()
        } else {
            record.clone()
        };
        for group in manifest::GROUPS {
            let old_deps = old.and_then(|v| v.get(group)).and_then(Value::as_object);
            let new_deps = new.and_then(|v| v.get(group)).and_then(Value::as_object);
            let names: BTreeSet<_> = old_deps
                .into_iter()
                .chain(new_deps.filter(|_| changed.contains_key(id.as_str())))
                .flat_map(|v| v.keys())
                .collect();
            let mut merged_deps = Map::new();
            let mut keep = Map::new();
            let mut take = Map::new();
            for name in names {
                let previous = old_deps.and_then(|v| v.get(name));
                let next = new_deps.and_then(|v| v.get(name));
                let declared = changed.contains_key(id.as_str())
                    && previous.and_then(|v| v.get("specifier"))
                        != next.and_then(|v| v.get("specifier"));
                let local = [previous.map(|v| (base, v)), next.map(|v| (donor, v))]
                    .into_iter()
                    .flatten()
                    .filter_map(|(doc, dep)| local_target(doc, id, name, dep))
                    .any(|target| affected.contains(&target));
                let peers = affected.contains(id)
                    && [(base, previous, &peer_base), (donor, next, &peer_donor)]
                        .into_iter()
                        .any(|(doc, dep, keys)| {
                            dep.and_then(|v| v.get("version"))
                                .and_then(Value::as_str)
                                .is_some_and(|r| {
                                    keys.contains(&graph::snapshot_key(
                                        name,
                                        r,
                                        graph::section(doc, "snapshots"),
                                    ))
                                })
                        });
                let dependency_metadata = changed.get(id.as_str()).is_some_and(|change| {
                    ["dependenciesMeta", "peerDependenciesMeta"]
                        .iter()
                        .any(|field| {
                            get(change.before, field).and_then(|v| v.get(name))
                                != get(change.after, field).and_then(|v| v.get(name))
                        })
                });
                let installed_peer = affected.contains(id)
                    && providers.contains(name)
                    && manifests.get(id.as_str()).is_some_and(|change| {
                        get(change.after, "peerDependencies")
                            .and_then(|v| v.get(name))
                            .is_some()
                            && manifest::GROUPS.iter().all(|field| {
                                get(change.after, field).and_then(|v| v.get(name)).is_none()
                            })
                    });
                let use_candidate =
                    declared || dependency_metadata || local || peers || installed_peer;
                if use_candidate
                    && !changed.contains_key(id.as_str())
                    && previous.and_then(|v| v.get("specifier"))
                        != next.and_then(|v| v.get("specifier"))
                {
                    return Err(manifest::mismatch(
                        id,
                        "candidate",
                        format!("affected dependency {name} changed without a manifest change"),
                    ));
                }
                if let Some(dep) = if use_candidate { next } else { previous } {
                    merged_deps.insert(name.clone(), dep.clone());
                    if use_candidate {
                        take.insert(name.clone(), dep.clone());
                    } else {
                        keep.insert(name.clone(), dep.clone());
                    }
                }
            }
            if merged_deps.is_empty() {
                merged.as_object_mut().unwrap().remove(group);
            } else {
                merged[group] = Value::Object(merged_deps);
            }
            if !keep.is_empty() {
                old_edges.insert(group.into(), Value::Object(keep));
            }
            if !take.is_empty() {
                new_edges.insert(group.into(), Value::Object(take));
            }
        }
        *record = merged;
        retained.insert(id.clone(), Value::Object(old_edges));
        adopted.insert(id.clone(), Value::Object(new_edges));
    }
    let result = graft::from_edges(
        baseline,
        candidate,
        output,
        &Value::Object(retained),
        &Value::Object(adopted),
    )?;
    for change in changes {
        manifest::check(
            result.project().unwrap(),
            change.importer,
            change.after,
            "output",
        )?;
    }
    Ok(result)
}

fn get<'a>(manifest: Option<&'a Value>, field: &str) -> Option<&'a Value> {
    manifest.and_then(|v| v.get(field))
}

fn local_target(document: &Value, importer: &str, name: &str, dep: &Value) -> Option<String> {
    let reference = dep.get("version")?.as_str()?;
    if let Some(path) = reference.strip_prefix("link:") {
        return Some(graph::linked_importer(importer, path));
    }
    let key = graph::snapshot_key(name, reference, graph::section(document, "snapshots"));
    local_package(document, &key)
}

fn local_package(document: &Value, key: &str) -> Option<String> {
    document
        .get("packages")?
        .get(graph::package_key(key))?
        .get("resolution")?
        .get("directory")?
        .as_str()
        .map(|path| graph::linked_importer(".", path))
}

/// Mark packages with affected peers/local sources, then walk reverse edges.
/// A parent can require a new peer instance through a transitive dependency.
fn affected_snapshots(
    document: &Value,
    providers: &BTreeSet<String>,
    locals: &BTreeSet<String>,
) -> BTreeSet<String> {
    let records: Vec<_> = graph::section(document, "snapshots")
        .into_iter()
        .flatten()
        .collect();
    let mut visited = vec![false; records.len()];
    let mut pending = Vec::new();
    for (id, (key, _)) in records.iter().enumerate() {
        let peers = document
            .get("packages")
            .and_then(|v| v.get(graph::package_key(key)))
            .and_then(|v| v.get("peerDependencies"))
            .and_then(Value::as_object);
        if peers.is_some_and(|m| m.keys().any(|n| providers.contains(n)))
            || local_package(document, key).is_some_and(|id| locals.contains(&id))
        {
            visited[id] = true;
            pending.push(id);
        }
    }
    if pending.is_empty() {
        return BTreeSet::new();
    }
    // Borrow identities and store reverse edges as dense IDs. Long peer suffixes
    // are not copied for each incoming edge or queue entry.
    let index: HashMap<_, _> = records
        .iter()
        .enumerate()
        .map(|(id, (key, _))| (key.as_str(), id))
        .collect();
    let mut reverse = vec![Vec::new(); records.len()];
    for (id, (_, record)) in records.iter().enumerate() {
        for group in ["dependencies", "optionalDependencies"] {
            for (name, reference) in record
                .get(group)
                .and_then(Value::as_object)
                .into_iter()
                .flatten()
            {
                if let Some(reference) = reference.as_str()
                    && let Some(target) = index
                        .get(format!("{name}@{reference}").as_str())
                        .or_else(|| index.get(reference))
                {
                    reverse[*target].push(id);
                }
            }
        }
    }
    while let Some(id) = pending.pop() {
        for &parent in &reverse[id] {
            if !visited[parent] {
                visited[parent] = true;
                pending.push(parent);
            }
        }
    }
    records
        .into_iter()
        .zip(visited)
        .filter(|(_, visited)| *visited)
        .map(|((key, _), _)| key.clone())
        .collect()
}
