/// Before/after package.json values supplied by the caller. `None` denotes
/// addition/deletion. Include unchanged local dependency manifests when their
/// candidate importer changes: peer declarations are not stored in importers.
#[derive(Debug, Clone, Copy)]
pub struct ManifestChange<'a> {
    /// Workspace-relative importer ID, or `.` for the root.
    pub importer: &'a str,
    /// Baseline manifest, or `None` for a newly added project.
    pub before: Option<&'a Value>,
    /// Installed workspace manifest, or `None` for a removed project.
    pub after: Option<&'a Value>,
}

const METADATA: [&str; 15] = [
    "peerDependencies",
    "peerDependenciesMeta",
    "dependenciesMeta",
    "name",
    "version",
    "bin",
    "engines",
    "os",
    "cpu",
    "libc",
    "bundledDependencies",
    "bundleDependencies",
    "publishConfig",
    "type",
    "exports",
];

/// Effective workspace settings and optional published manifests for convergence.
#[derive(Debug, Default, Clone, Copy)]
pub struct ConvergeOptions<'a> {
    /// Effective configuration at the baseline ref. Omit when the configuration is unchanged.
    pub baseline_configuration: Option<&'a crate::WorkspaceConfig>,
    /// Effective configuration used to generate the installed candidate.
    pub configuration: Option<&'a crate::WorkspaceConfig>,
    /// Published release metadata available for recovering original dependency ranges.
    pub registry: Option<&'a crate::RegistryMetadata>,
}

/// Reduce an installed lockfile to the changes required by manifests and
/// workspace rules. Manifest declarations must match their
/// respective locks. Edited registry ranges retain an admissible baseline
/// pin. Changed local dependencies and peer contexts use the candidate graph
/// as necessary.
///
/// The caller supplies all manifest changes and a candidate generated by pnpm.
/// Supply both workspace configurations for catalog, override, or package
/// extension edits. Each consumer retains its eligible peer bindings. Other
/// resolution settings must agree. Registry evidence can supply the published
/// child ranges of a new parent release or of a removed override.
///
/// # Errors
/// Mismatched manifests or incompatible configuration changes return an error. Missing
/// locked evidence can produce a resolution request. Incompatible graph records produce a conflict.
pub fn converge(
    baseline: &Lockfile,
    candidate: &Lockfile,
    changes: &[ManifestChange<'_>],
    options: ConvergeOptions<'_>,
) -> Result<Lockfile, LockfileError> {
    converge_with_patches(baseline, candidate, changes, options, &BTreeMap::new())
}

/// Converge with the final workspace's patch contents, keyed by relative path.
/// A pnpm version migration uses all final manifests and verifies patch identities.
///
/// # Errors
/// Returns the errors of [`converge`] and rejects unavailable or inconsistent patch data.
pub fn converge_with_patches(
    baseline: &Lockfile,
    candidate: &Lockfile,
    changes: &[ManifestChange<'_>],
    options: ConvergeOptions<'_>,
    patches: &BTreeMap<String, String>,
) -> Result<Lockfile, LockfileError> {
    converge_with_recorded_baselines(
        baseline,
        candidate,
        changes,
        options,
        patches,
        &BTreeSet::new(),
    )
}

#[derive(Clone, Copy)]
struct ChangeSet<'a> {
    manifests: &'a [ManifestChange<'a>],
    recorded: &'a BTreeSet<String>,
}

impl ChangeSet<'_> {
    fn check_baseline(
        &self,
        rules: &manifest::Overrides<'_>,
        change: &ManifestChange<'_>,
    ) -> Result<(), LockfileError> {
        let mode = if self.recorded.contains(change.importer) {
            manifest::ManifestCheck::RecordedBaseline
        } else {
            manifest::ManifestCheck::Authored
        };
        manifest::check_manifest(rules, change.importer, change.before, "baseline", mode)
    }
}

/// Converge when some baseline manifests were reconstructed from their lockfile
/// importers. For each ID in `recorded_baselines`, the dependency groups in
/// `ManifestChange::before` contain the effective specifiers recorded by pnpm.
/// The final manifests and all other baseline manifests contain authored declarations.
///
/// # Errors
/// Returns the errors of [`converge_with_patches`], including mismatches between
/// a reconstructed baseline and its recorded groups, specifiers, or metadata.
pub fn converge_with_recorded_baselines(
    baseline: &Lockfile,
    candidate: &Lockfile,
    changes: &[ManifestChange<'_>],
    options: ConvergeOptions<'_>,
    patches: &BTreeMap<String, String>,
    recorded_baselines: &BTreeSet<String>,
) -> Result<Lockfile, LockfileError> {
    let inputs = ChangeSet {
        manifests: changes,
        recorded: recorded_baselines,
    };
    if let Some(root) = changes
        .iter()
        .find(|c| c.importer == ".")
        .and_then(|c| c.after)
    {
        candidate.check_package_manager(root, options.configuration)?;
    }
    if let (Some(config), Some(project)) = (options.configuration, candidate.project()) {
        if !config.matches_config_dependencies(candidate.environment()) {
            return Err(crate::reconcile::missing(
                &["importers", ".", "configDependencies"],
                "installed bootstrap graph differs from the configuration dependencies",
            ));
        }
        crate::repair::check_recorded_settings(project, config)?;
    }
    if let Some((before, after)) = options.baseline_configuration.zip(options.configuration)
        && (before.changes_pnpm_version(after)
            || baseline.recorded_pnpm_version() != candidate.recorded_pnpm_version()
            || before.config_dependencies != after.config_dependencies)
    {
        let installed = candidate.project().ok_or_else(|| {
            crate::reconcile::missing(&["importers"], "missing candidate project")
        })?;
        let original = baseline
            .project()
            .ok_or_else(|| crate::reconcile::missing(&["importers"], "missing baseline project"))?;
        let baseline_rules = manifest::Overrides::new(original, before);
        let rules = manifest::Overrides::new(installed, after);
        let mut manifests = BTreeMap::new();
        let mut seen = BTreeSet::new();
        for change in changes {
            if !seen.insert(change.importer) {
                return Err(LockfileError::InvalidManifest(change.importer.into()));
            }
            inputs.check_baseline(&baseline_rules, change)?;
            manifest::check(&rules, change.importer, change.after, "candidate")?;
            if let Some(manifest) = change.after {
                manifests.insert(change.importer.to_owned(), manifest.clone());
            }
        }
        if let Some(id) = graph::keys(installed, "importers")
            .into_iter()
            .find(|id| !manifests.contains_key(id))
        {
            return Err(crate::reconcile::missing(
                &["manifests", &id],
                "pnpm migration requires every final workspace manifest",
            ));
        }
        return crate::reconcile::converge_upgrade(
            baseline,
            candidate,
            &crate::MergeContext {
                target: crate::MergeTarget::Ours,
                configurations: [before, before, after],
                configuration: after,
                manifests: &manifests,
                patches,
                registry: options.registry,
            },
        );
    }
    let mut result = select(baseline, candidate, inputs, options)?;
    if let Some(config) = options.configuration {
        let project = result.project().expect("converged project");
        crate::repair::check_recorded_settings(project, config)?;
        let mut plan = crate::extensions::plan(project, config, candidate.project(), None)?;
        if !plan.is_empty() {
            let project = std::sync::Arc::make_mut(
                result
                    .documents
                    .get_mut(&crate::DocumentKind::Project)
                    .expect("converged project"),
            );
            workspace::checked_checksum(project, config)?;
            let root = changes
                .iter()
                .find(|change| change.importer == ".")
                .and_then(|change| change.after);
            workspace::checked_overrides(project, config, root)?;
            while plan.apply(project) {
                plan = crate::extensions::plan(project, config, candidate.project(), None)?;
            }
            graph::prune_scoped(
                project,
                crate::DocumentKind::Project,
                baseline.project().expect("baseline project"),
                Some(config),
            )?;
        }
    }
    let project = result
        .documents
        .get_mut(&crate::DocumentKind::Project)
        .expect("converged project");
    let base = baseline.project().expect("baseline project");
    let installed = candidate.project().expect("candidate project");
    // A reinstall can record timestamps even when every importer stays at its baseline pin.
    let donor =
        if installed.get("time").is_some() && project.get("importers") == base.get("importers") {
            base
        } else {
            installed
        };
    if let Some(times) =
        crate::reconcile::metadata::publication_times(project, [base, donor], options.configuration)
        && project.get("time") != Some(&times)
    {
        std::sync::Arc::make_mut(project)["time"] = times;
    }
    Ok(result)
}

fn select(
    baseline: &Lockfile,
    candidate: &Lockfile,
    inputs: ChangeSet<'_>,
    options: ConvergeOptions<'_>,
) -> Result<Lockfile, LockfileError> {
    let configured = if let Some(before) = options.baseline_configuration {
        let after = options.configuration.ok_or_else(|| {
            crate::reconcile::missing(
                &["configuration"],
                "the final workspace configuration is required",
            )
        })?;
        match workspace::apply(baseline, candidate, before, after, inputs, options.registry) {
            Ok(plan) => plan,
            Err(workspace::ProjectionError::Input(error)) => return Err(error),
            Err(workspace::ProjectionError::MixedPeers) => {
                return installed::converge(baseline, candidate, inputs, before, after);
            }
        }
    } else {
        None
    };
    let (projected, configured) = match configured {
        Some((lock, rules)) => (lock, Some(rules)),
        None => (baseline.clone(), None),
    };
    let mut result = match converge_manifests(
        baseline,
        projected,
        candidate,
        inputs,
        options,
        configured.as_ref(),
    ) {
        Err(LockfileError::Conflicts(conflicts))
            if configured.is_some()
                && conflicts.iter().all(|c| {
                    c.kind == crate::ConflictKind::SharedDependency
                        && c.path.first().is_some_and(|p| p == "snapshots")
                }) =>
        {
            return installed::converge(
                baseline,
                candidate,
                inputs,
                options.baseline_configuration.unwrap(),
                options.configuration.unwrap(),
            );
        }
        result => result?,
    };
    if let Some(projection) = configured {
        projection.bind_roots(
            &mut result,
            baseline,
            candidate,
            options.configuration.expect("verified configuration"),
        )?;
    }
    let default_config = crate::WorkspaceConfig::default();
    let overrides = manifest::Overrides::new(
        result.project().unwrap(),
        options.configuration.unwrap_or(&default_config),
    );
    for change in inputs.manifests {
        manifest::check(&overrides, change.importer, change.after, "output")?;
    }
    Ok(result)
}

fn check_baseline_manifest(
    overrides: &manifest::Overrides<'_>,
    change: &ManifestChange<'_>,
    baseline_configuration: Option<&crate::WorkspaceConfig>,
    inputs: ChangeSet<'_>,
) -> Result<(), LockfileError> {
    if change.before.is_none() && change.after.is_none() {
        return Err(LockfileError::InvalidManifest(change.importer.into()));
    }
    for value in [change.before, change.after].into_iter().flatten() {
        if !value.is_object() {
            return Err(LockfileError::InvalidManifest(change.importer.into()));
        }
    }
    for field in ["pnpm", "packageManager", "devEngines"] {
        if field == "pnpm"
            && overrides
                .configuration()
                .pnpm_version
                .as_ref()
                .is_some_and(|v| v.major() >= 11)
        {
            continue;
        }
        if field == "packageManager" && change.importer != "." {
            continue;
        }
        if get(change.before, field) != get(change.after, field) {
            if field == "pnpm"
                && change.importer == "."
                && baseline_configuration.is_some()
                && [change.before, change.after]
                    .iter()
                    .all(|m| get(*m, field).is_none_or(Value::is_object))
                && [change.before, change.after]
                    .into_iter()
                    .flat_map(|m| {
                        get(m, field)
                            .and_then(Value::as_object)
                            .into_iter()
                            .flatten()
                    })
                    .all(|(key, _)| {
                        matches!(
                            key.as_str(),
                            "packageExtensions" | "overrides" | "catalog" | "catalogs"
                        ) || get(change.before, field).and_then(|v| v.get(key))
                            == get(change.after, field).and_then(|v| v.get(key))
                    })
            {
                continue;
            }
            return Err(LockfileError::GlobalConfigurationChanged {
                importer: change.importer.into(),
                field: field.into(),
            });
        }
    }
    inputs.check_baseline(overrides, change)
}

struct LocalGraph<'a> {
    document: &'a Value,
    projects: graph::LinkedProjects<'a>,
}
impl<'a> LocalGraph<'a> {
    fn new(document: &'a Value) -> Self {
        Self {
            document,
            projects: graph::LinkedProjects::new(document.get("importers")),
        }
    }
    fn target(&self, importer: &str, name: &str, dep: &Value) -> Option<String> {
        let reference = dep.get("version")?.as_str()?;
        if let Some(path) = reference.strip_prefix("link:") {
            return Some(self.projects.resolve(importer, path));
        }
        let key = graph::snapshot_key(name, reference, graph::section(self.document, "snapshots"));
        local_package(self.document, &key)
    }
}

type SpecifierEdits<'a> = BTreeMap<(&'a str, &'static str, &'a str), (&'a Value, &'a str)>;
struct ManifestEdits<'a> {
    changed: BTreeMap<&'a str, &'a ManifestChange<'a>>,
    manifests: BTreeMap<&'a str, &'a ManifestChange<'a>>,
    specifiers: SpecifierEdits<'a>,
    only_specifiers: bool,
    metadata_importers: BTreeSet<&'a str>,
    providers: BTreeMap<String, BTreeSet<&'a str>>,
    forced: BTreeSet<(&'a str, &'a str)>,
}

fn manifest_edits<'a>(
    graphs: [&LocalGraph<'a>; 2],
    rules: [&manifest::Overrides<'_>; 2],
    inputs: ChangeSet<'a>,
    configured: Option<&'a workspace::Projection>,
    baseline_configuration: Option<&crate::WorkspaceConfig>,
) -> Result<ManifestEdits<'a>, LockfileError> {
    let [base, donor] = graphs.map(|g| g.document);
    let [baseline_rules, candidate_rules] = rules;
    let root_choices = configured.map(|p| &p.roots);
    let mut changed = BTreeMap::new();
    let mut specifiers = BTreeMap::new();
    let mut only_specifiers = true;
    let mut metadata_importers = BTreeSet::new();
    let mut providers: BTreeMap<String, BTreeSet<&str>> = BTreeMap::new();
    let mut manifests = BTreeMap::new();
    for change in inputs.manifests {
        if manifests.insert(change.importer, change).is_some() {
            return Err(LockfileError::InvalidManifest(change.importer.into()));
        }
        check_baseline_manifest(baseline_rules, change, baseline_configuration, inputs)?;
        let recorded = inputs.recorded.contains(change.importer);
        let metadata = METADATA
            .iter()
            .any(|key| get(change.before, key) != get(change.after, key))
            || get(change.before, "scripts").and_then(|v| v.get("prepare"))
                != get(change.after, "scripts").and_then(|v| v.get("prepare"));
        let same_project = change.before.is_some()
            && change.after.is_some()
            && !metadata
            && root_choices.and_then(|r| r.get(change.importer)).is_none();
        if same_project
            && !recorded
            && manifest::GROUPS
                .iter()
                .all(|key| get(change.before, key) == get(change.after, key))
        {
            continue;
        }
        manifest::check(candidate_rules, change.importer, change.after, "candidate")?;
        let mut names = BTreeSet::new();
        for field in manifest::GROUPS.into_iter().chain(["peerDependencies"]) {
            // The verified importer contains the candidate's effective specifiers.
            // Peer declarations are only available in the manifest itself.
            let from_importer = recorded && field != "peerDependencies";
            let after = if from_importer {
                donor["importers"].get(change.importer)
            } else {
                change.after
            };
            for manifest in [change.before, after].into_iter().flatten() {
                for name in graph::section(manifest, field)
                    .into_iter()
                    .flat_map(|deps| deps.keys())
                {
                    let next = get(after, field).and_then(|v| v.get(name));
                    let specifier = if from_importer {
                        next.and_then(|v| v.get("specifier"))
                    } else {
                        next
                    };
                    if get(change.before, field).and_then(|v| v.get(name)) != specifier {
                        names.insert(name);
                    }
                }
            }
        }
        if same_project && names.is_empty() {
            continue;
        }
        if metadata || change.before.is_none() {
            metadata_importers.insert(change.importer);
        }
        only_specifiers &= !metadata && change.before.is_some() && change.after.is_some();
        for name in names {
            let old = importer_dependency(base, change.importer, name);
            let new = importer_dependency(donor, change.importer, name);
            let peer_changed = get(change.before, "peerDependencies").and_then(|v| v.get(name))
                != get(change.after, "peerDependencies").and_then(|v| v.get(name));
            if !peer_changed
                && let (Some((old_group, previous)), Some((new_group, next))) = (old, new)
                && let (Some(pin), Some(declaration)) =
                    (previous["version"].as_str(), next["specifier"].as_str())
                && crate::reconcile::accepts(name, declaration, pin, base)
                && graphs[0].target(change.importer, name, previous).is_none()
                && graphs[1].target(change.importer, name, next).is_none()
            {
                only_specifiers &= old_group == new_group;
                specifiers.insert(
                    (change.importer, new_group, name.as_str()),
                    (previous, declaration),
                );
                continue;
            }
            only_specifiers = false;
            providers
                .entry(name.clone())
                .or_default()
                .insert(change.importer);
            for (doc, dependency) in [(base, old), (donor, new)] {
                let Some(pin) = dependency.and_then(|(_, record)| record["version"].as_str())
                else {
                    continue;
                };
                let key = graph::snapshot_key(name, pin, graph::section(doc, "snapshots"));
                if let Some((actual, _)) = graph::package_key(&key).rsplit_once('@') {
                    providers
                        .entry(actual.into())
                        .or_default()
                        .insert(change.importer);
                }
            }
        }
        for m in [change.before, change.after].into_iter().flatten() {
            if let Some(name) = m.get("name").and_then(Value::as_str) {
                providers
                    .entry(name.into())
                    .or_default()
                    .insert(change.importer);
            }
        }
        changed.insert(change.importer, change);
    }
    let mut forced = BTreeSet::new();
    if let Some(roots) = root_choices {
        for (id, choices) in roots {
            for (name, choice) in choices {
                if *choice == workspace::RootChoice::Installed {
                    forced.insert((id.as_str(), name.as_str()));
                    providers.entry(name.clone()).or_default().insert(id);
                    only_specifiers = false;
                } else if let (Some(old), Some((group, new))) = (
                    match choice {
                        workspace::RootChoice::CatalogPin(pin) => {
                            only_specifiers = false;
                            Some(pin)
                        }
                        _ => importer_dependency(base, id, name).map(|(_, dep)| dep),
                    },
                    importer_dependency(donor, id, name),
                ) {
                    specifiers.insert(
                        (id, group, name),
                        (
                            old,
                            new["specifier"].as_str().ok_or_else(|| {
                                manifest::mismatch(id, "candidate", "missing specifier")
                            })?,
                        ),
                    );
                }
            }
        }
    }
    Ok(ManifestEdits {
        changed,
        manifests,
        specifiers,
        only_specifiers,
        metadata_importers,
        providers,
        forced,
    })
}

struct LocalChanges {
    affected: BTreeSet<String>,
    consumers: BTreeMap<String, BTreeSet<String>>,
}

fn local_changes(
    graphs: [&LocalGraph; 2],
    edits: &ManifestEdits,
    candidate_rules: &manifest::Overrides,
) -> Result<LocalChanges, LockfileError> {
    let [base, donor] = graphs.map(|g| g.document);
    // Propagate local package changes through workspace consumers, including
    // injected/file packages. This changes edge provenance, not entire importers.
    let mut reverse: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut forward: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for graph in graphs {
        let document = graph.document;
        for (id, record) in graph::section(document, "importers").into_iter().flatten() {
            for group in manifest::GROUPS {
                for (name, dep) in record
                    .get(group)
                    .and_then(Value::as_object)
                    .into_iter()
                    .flatten()
                {
                    if let Some(target) = graph.target(id, name, dep) {
                        reverse
                            .entry(target.clone())
                            .or_default()
                            .insert(id.clone());
                        forward.entry(id.clone()).or_default().insert(target);
                    }
                }
            }
        }
    }
    let mut affected: BTreeSet<String> = edits.changed.keys().map(|s| (*s).into()).collect();
    let mut queue: VecDeque<_> = affected.iter().cloned().collect();
    let mut descendants = affected.clone();
    while let Some(parent) = queue.pop_front() {
        for target in forward.get(&parent).into_iter().flatten() {
            if !descendants.insert(target.clone()) {
                continue;
            }
            queue.push_back(target.clone());
            let old = base.get("importers").and_then(|v| v.get(target));
            let new = donor.get("importers").and_then(|v| v.get(target));
            if old != new {
                let context = edits.manifests.get(target.as_str()).ok_or_else(|| {
                    manifest::mismatch(
                        target,
                        "candidate",
                        "include before/after manifests for this affected local dependency",
                    )
                })?;
                manifest::check(candidate_rules, target, context.after, "candidate")?;
                affected.insert(target.clone());
            }
        }
    }
    let mut queue: VecDeque<_> = affected.iter().cloned().collect();
    while let Some(target) = queue.pop_front() {
        for parent in reverse.get(&target).into_iter().flatten() {
            if affected.insert(parent.clone()) {
                queue.push_back(parent.clone());
            }
        }
    }
    Ok(LocalChanges {
        affected,
        consumers: reverse,
    })
}

struct SelectedEdges {
    output: Value,
    retained: Map<String, Value>,
    adopted: Map<String, Value>,
    local_base: BTreeSet<String>,
    local_donor: BTreeSet<String>,
}

fn select_edges(
    graphs: [&LocalGraph; 2],
    edits: &ManifestEdits,
    locals: LocalChanges,
    configured: Option<&workspace::Projection>,
    configuration: Option<&crate::WorkspaceConfig>,
) -> Result<SelectedEdges, LockfileError> {
    let [base, donor] = graphs.map(|g| g.document);
    let LocalChanges {
        affected,
        consumers: reverse,
    } = locals;
    let local_base = affected_snapshots(base, &affected);
    let local_donor = affected_snapshots(donor, &affected);
    let mut output = base.get("importers").cloned().unwrap_or_else(|| json!({}));
    for (id, change) in &edits.changed {
        if change.after.is_none() {
            output.as_object_mut().unwrap().remove(*id);
        } else if change.before.is_none() {
            output[*id] = donor["importers"][*id].clone();
        }
    }
    let mut retained = Map::new();
    let mut adopted = Map::new();
    for (id, record) in output.as_object_mut().expect("importer map") {
        let workspace_root = configured
            .map(|p| &p.roots)
            .is_some_and(|roots| roots.contains_key(id));
        let old = base.get("importers").and_then(|v| v.get(id));
        let new = donor.get("importers").and_then(|v| v.get(id));
        let mut old_edges = Map::new();
        let mut new_edges = Map::new();
        let mut merged = if edits.metadata_importers.contains(id.as_str()) {
            new.expect("manifest-checked candidate").clone()
        } else {
            record.clone()
        };
        for group in manifest::GROUPS {
            let old_deps = old.and_then(|v| v.get(group)).and_then(Value::as_object);
            let new_deps = new.and_then(|v| v.get(group)).and_then(Value::as_object);
            let names: BTreeSet<_> = old_deps
                .into_iter()
                .chain(
                    new_deps.filter(|_| edits.changed.contains_key(id.as_str()) || workspace_root),
                )
                .flat_map(|v| v.keys())
                .collect();
            let mut merged_deps = Map::new();
            let mut keep = Map::new();
            let mut take = Map::new();
            for name in names {
                let retained_specifier = edits.specifiers.get(&(id.as_str(), group, name.as_str()));
                let previous = retained_specifier
                    .map(|(old, _)| *old)
                    .or_else(|| old_deps.and_then(|v| v.get(name)));
                let next = new_deps.and_then(|v| v.get(name));
                let declared = edits.changed.contains_key(id.as_str())
                    && previous.and_then(|v| v.get("specifier"))
                        != next.and_then(|v| v.get("specifier"));
                let local = [
                    previous.map(|v| (graphs[0], v)),
                    next.map(|v| (graphs[1], v)),
                ]
                .into_iter()
                .flatten()
                .filter_map(|(doc, dep)| doc.target(id, name, dep))
                .any(|target| affected.contains(&target));
                let local_snapshot = affected.contains(id)
                    && [(base, previous, &local_base), (donor, next, &local_donor)]
                        .into_iter()
                        .any(|(doc, dep, keys)| {
                            dep.and_then(|v| v.get("version"))
                                .and_then(Value::as_str)
                                .is_some_and(|r| {
                                    keys.contains(&graph::snapshot_key(
                                        name,
                                        r,
                                        graph::section(doc, "snapshots"),
                                    ))
                                })
                        });
                let dependency_metadata = edits.changed.get(id.as_str()).is_some_and(|change| {
                    ["dependenciesMeta", "peerDependenciesMeta"]
                        .iter()
                        .any(|field| {
                            get(change.before, field).and_then(|v| v.get(name))
                                != get(change.after, field).and_then(|v| v.get(name))
                        })
                });
                let installed_peer = previous != next
                    && edits.manifests.get(id.as_str()).is_some_and(|change| {
                        get(change.after, "peerDependencies")
                            .and_then(|v| v.get(name))
                            .is_some()
                            && manifest::GROUPS.iter().all(|field| {
                                get(change.after, field).and_then(|v| v.get(name)).is_none()
                            })
                    })
                    && edits.providers.get(name).is_some_and(|sources| {
                        let inherit =
                            configuration.is_none_or(|c| c.resolution.workspace_root_peers);
                        (inherit && sources.contains("."))
                            || supplied_by_consumer(id, name, sources, &reverse, donor)
                    });
                let workspace_choice = edits.forced.contains(&(id.as_str(), name.as_str()));
                let use_candidate = workspace_choice
                    || (declared && retained_specifier.is_none())
                    || dependency_metadata
                    || local
                    || local_snapshot
                    || installed_peer;
                if use_candidate
                    && !workspace_choice
                    && !edits.changed.contains_key(id.as_str())
                    && previous.and_then(|v| v.get("specifier"))
                        != next.and_then(|v| v.get("specifier"))
                {
                    return Err(manifest::mismatch(
                        id,
                        "candidate",
                        format!("affected dependency {name} changed without a manifest change"),
                    ));
                }
                if let Some(dep) = if use_candidate { next } else { previous } {
                    let mut entry = dep.clone();
                    if !use_candidate && let Some(&(_, specifier)) = retained_specifier {
                        entry["specifier"] = Value::from(specifier);
                    }
                    merged_deps.insert(name.clone(), entry);
                    if use_candidate {
                        take.insert(name.clone(), dep.clone());
                    } else {
                        keep.insert(name.clone(), dep.clone());
                    }
                }
            }
            if merged_deps.is_empty() {
                merged.as_object_mut().unwrap().remove(group);
            } else {
                merged[group] = Value::Object(merged_deps);
            }
            if !keep.is_empty() {
                old_edges.insert(group.into(), Value::Object(keep));
            }
            if !take.is_empty() {
                new_edges.insert(group.into(), Value::Object(take));
            }
        }
        *record = merged;
        retained.insert(id.clone(), Value::Object(old_edges));
        adopted.insert(id.clone(), Value::Object(new_edges));
    }
    Ok(SelectedEdges {
        output,
        retained,
        adopted,
        local_base,
        local_donor,
    })
}

fn converge_manifests(
    original: &Lockfile,
    baseline: Lockfile,
    candidate: &Lockfile,
    inputs: ChangeSet<'_>,
    options: ConvergeOptions<'_>,
    configured: Option<&workspace::Projection>,
) -> Result<Lockfile, LockfileError> {
    let default_config = crate::WorkspaceConfig::default();
    let config = options.configuration.unwrap_or(&default_config);
    let base = baseline.project().ok_or_else(|| {
        LockfileError::InvalidDocument("missing baseline project document".into())
    })?;
    let donor = candidate.project().ok_or_else(|| {
        LockfileError::InvalidDocument("missing candidate project document".into())
    })?;
    let baseline_rules = manifest::Overrides::new(
        original.project().expect("baseline project"),
        options.baseline_configuration.unwrap_or(config),
    );
    let candidate_rules = manifest::Overrides::new(donor, config);
    let base_graph = LocalGraph::new(base);
    let donor_graph = LocalGraph::new(donor);
    let graphs = [&base_graph, &donor_graph];
    let edits = manifest_edits(
        graphs,
        [&baseline_rules, &candidate_rules],
        inputs,
        configured,
        options.baseline_configuration,
    )?;
    if configured.is_none() {
        baseline.validate_with_config(options.configuration)?;
        if edits.changed.is_empty() {
            return Ok(baseline);
        }
    }
    if edits.only_specifiers {
        let edits: Vec<_> = edits
            .specifiers
            .into_iter()
            .filter(|(_, (old, spec))| old["specifier"].as_str() != Some(spec))
            .map(|((id, group, name), (_, spec))| {
                ((id.to_owned(), group, name.to_owned()), Value::from(spec))
            })
            .collect();
        if edits.is_empty() && configured.is_none() {
            return Ok(baseline);
        }
        let mut result = baseline;
        let project = std::sync::Arc::make_mut(
            result
                .documents
                .get_mut(&crate::DocumentKind::Project)
                .expect("project checked"),
        );
        for ((id, group, name), specifier) in edits {
            project["importers"][id][group][name]["specifier"] = specifier;
        }
        if configured.is_some() {
            graph::prune_scoped(
                project,
                crate::DocumentKind::Project,
                original.project().unwrap(),
                options.configuration,
            )?;
        }
        return Ok(result);
    }

    let locals = local_changes(graphs, &edits, &candidate_rules)?;
    let SelectedEdges {
        mut output,
        mut retained,
        mut adopted,
        mut local_base,
        mut local_donor,
    } = select_edges(graphs, &edits, locals, configured, options.configuration)?;
    let generated = peers::bind(
        [base, donor],
        &mut output,
        &mut retained,
        &mut adopted,
        options.configuration,
    )?;
    if let Some(p) = configured {
        local_base.extend(p.unprojected.iter().cloned());
        local_donor.extend(p.unprojected.iter().cloned());
    }
    let result = assembly::from_edges(
        (baseline, candidate),
        original.project().unwrap(),
        output,
        [&Value::Object(retained), &Value::Object(adopted)],
        options,
        [&local_base, &local_donor],
        generated,
    )?;
    Ok(result)
}

fn get<'a>(manifest: Option<&'a Value>, field: &str) -> Option<&'a Value> {
    manifest.and_then(|v| v.get(field))
}

/// A linked workspace can obtain its auto-installed peer from a consumer.
/// An intermediate consumer's own pin shadows providers further up the path.
fn supplied_by_consumer<'a>(
    id: &'a str,
    name: &str,
    sources: &BTreeSet<&str>,
    consumers: &'a BTreeMap<String, BTreeSet<String>>,
    candidate: &Value,
) -> bool {
    let mut pending = vec![id];
    let mut seen = BTreeSet::new();
    while let Some(path) = pending.pop() {
        if sources.contains(path) {
            return true;
        }
        if seen.insert(path) && (path == id || importer_dependency(candidate, path, name).is_none())
        {
            pending.extend(
                consumers
                    .get(path)
                    .into_iter()
                    .flatten()
                    .map(String::as_str),
            );
        }
    }
    false
}

fn importer_dependency<'a>(
    document: &'a Value,
    id: &str,
    name: &str,
) -> Option<(&'static str, &'a Value)> {
    let importer = &document["importers"][id];
    manifest::GROUPS
        .into_iter()
        .find_map(|group| importer[group].get(name).map(|dep| (group, dep)))
}

fn local_package(document: &Value, key: &str) -> Option<String> {
    document
        .get("packages")?
        .get(graph::package_key(key))?
        .get("resolution")?
        .get("directory")?
        .as_str()
        .map(|path| graph::linked_importer(".", path))
}

/// A directory package can change its dependencies without changing its locator.
fn affected_snapshots(document: &Value, locals: &BTreeSet<String>) -> BTreeSet<String> {
    affected_by(document, |key| {
        local_package(document, key).is_some_and(|id| locals.contains(&id))
    })
}

fn affected_by(document: &Value, seed: impl Fn(&str) -> bool) -> BTreeSet<String> {
    let records: Vec<_> = graph::section(document, "snapshots")
        .into_iter()
        .flatten()
        .collect();
    let mut visited = vec![false; records.len()];
    let mut pending = Vec::new();
    for (id, (key, _)) in records.iter().enumerate() {
        if seed(key) {
            visited[id] = true;
            pending.push(id);
        }
    }
    if pending.is_empty() {
        return BTreeSet::new();
    }
    // Borrow identities and store reverse edges as dense IDs. Long peer suffixes
    // are not copied for each incoming edge or queue entry.
    let index: HashMap<_, _> = records
        .iter()
        .enumerate()
        .map(|(id, (key, _))| (key.as_str(), id))
        .collect();
    let mut reverse = vec![Vec::new(); records.len()];
    for (id, (_, record)) in records.iter().enumerate() {
        for group in ["dependencies", "optionalDependencies"] {
            for (name, reference) in record
                .get(group)
                .and_then(Value::as_object)
                .into_iter()
                .flatten()
            {
                if let Some(reference) = reference.as_str()
                    && let Some(target) = index
                        .get(format!("{name}@{reference}").as_str())
                        .or_else(|| index.get(reference))
                {
                    reverse[*target].push(id);
                }
            }
        }
    }
    while let Some(id) = pending.pop() {
        for &parent in &reverse[id] {
            if !visited[parent] {
                visited[parent] = true;
                pending.push(parent);
            }
        }
    }
    records
        .into_iter()
        .zip(visited)
        .filter(|(_, visited)| *visited)
        .map(|((key, _), _)| key.clone())
        .collect()
}
