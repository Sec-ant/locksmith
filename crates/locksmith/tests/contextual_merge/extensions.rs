#[test]
fn composed_extension_checksums_follow_the_verified_input_format() {
    let before = json!({"packageExtensions":{"unused@1":{"dependencies":{"a":"1"},"peerDependenciesMeta":{"b":{"optional":true}}}}});
    let mut after = before.clone();
    after["packageExtensions"]["other@2"] = json!({"peerDependencies":{"runtime":"^1"},"peerDependenciesMeta":{"runtime":{"optional":true}}});
    let manifests = BTreeMap::from([(".".into(), json!({"private":true}))]);
    let patches = BTreeMap::new();
    // Generated by pnpm 9.15.9 and 10.34.9; pnpm 11/12 use the latter encoding.
    for (source, expected) in [
        (
            "0c4e68c99d1996cab37c5f3ce80e6f31",
            "a306aef78d4efb4a7a951d8f3eb8cb86",
        ),
        (
            "sha256-15/QBXY0x5rrD3ZgZ1ro+IFZoW8ZslDpM57ItK+lKs0=",
            "sha256-yJl50HvjuT+xbRr8O65eXEDHRUV1PXpJIaPnfqNrwC4=",
        ),
    ] {
        let input = json!({"lockfileVersion":"9.0", "importers":{".":{}}, "packageExtensionsChecksum":source});
        let lock = Lockfile::parse(&input.to_string()).unwrap();
        let before = cfg(&before);
        let after = cfg(&after);
        let context = MergeContext {
            registry: None,
            target: MergeTarget::Theirs,
            manifests: &manifests,
            configurations: [&before; 3],
            configuration: &after,
            patches: &patches,
        };
        let output = merge(&lock, &lock, &lock, Some(&context)).unwrap();
        assert_eq!(
            output.project().unwrap()["packageExtensionsChecksum"],
            expected
        );
        let mut invalid = input;
        invalid["packageExtensionsChecksum"] = json!("00000000000000000000000000000000");
        let invalid = Lockfile::parse(&invalid.to_string()).unwrap();
        assert!(matches!(
            merge(&invalid, &invalid, &invalid, Some(&context)),
            Err(LockfileError::ResolutionRequired { .. })
        ));
    }
}

#[test]
fn package_extensions_only_restrict_sources_for_matching_packages() {
    let base = lock(1, 1, false);
    let ours = lock(2, 1, false);
    let manifests = BTreeMap::from([(
        ".".into(),
        json!({"dependencies":{"a":"2.0.0","b":"1.0.0","lib":"1.0.0"}}),
    )]);
    let before = cfg(&json!({}));
    for (selector, compatible) in [("b@1", true), ("a@1", true), ("a@2", false)] {
        let final_config =
            cfg(&json!({"packageExtensions":{selector:{"dependencies":{"extra":"1.0.0"}}}}));
        let mut data = base.project().unwrap().clone();
        data["packageExtensionsChecksum"] = json!("sha256-final");
        if selector == "b@1" || selector == "a@1" {
            let name = selector.split('@').next().unwrap();
            data["snapshots"][format!("{name}@1.0.0")]["dependencies"] = json!({"extra":"1.0.0"});
            data["packages"]["extra@1.0.0"] = json!({"resolution":{"integrity":"sha512-extra"}});
            data["snapshots"]["extra@1.0.0"] = json!({});
        }
        let theirs = Lockfile::parse(&data.to_string()).unwrap();
        let patches = BTreeMap::new();
        let result = merge(
            &base,
            &ours,
            &theirs,
            Some(&MergeContext {
                registry: None,
                target: MergeTarget::Theirs,
                manifests: &manifests,
                configurations: [&before, &before, &final_config],
                configuration: &final_config,
                patches: &patches,
            }),
        );
        if compatible {
            let result = result.unwrap();
            result.validate().unwrap();
            let doc = result.project().unwrap();
            assert_eq!(
                doc["importers"]["."]["dependencies"]["a"]["version"],
                "2.0.0"
            );
            assert_eq!(doc["packageExtensionsChecksum"], "sha256-final");
            if selector == "b@1" {
                assert_eq!(
                    doc["snapshots"]["b@1.0.0"]["dependencies"]["extra"],
                    "1.0.0"
                );
            }
        } else {
            assert!(
                matches!(result, Err(LockfileError::ResolutionRequired { path, .. }) if path == ["snapshots", "a@2.0.0", "extra"])
            );
        }
    }
}

#[test]
fn changed_extensions_rebind_nested_instances_and_propagate_new_peers() {
    let make = |wrapper: u8, a: u8, b: u8, extended: bool| {
        let suffix = format!(
            "(a@{a}.0.0){}",
            if extended {
                format!("(b@{b}.0.0)")
            } else {
                String::new()
            }
        );
        let mut doc = json!({
            "lockfileVersion":"9.0",
            "settings":{"autoInstallPeers":true,"excludeLinksFromLockfile":false},
            "importers":{".":{"dependencies":{
                "a":{"specifier":"*","version":format!("{a}.0.0")},
                "b":{"specifier":"*","version":format!("{b}.0.0")},
                "wrapper":{"specifier":format!("{wrapper}.0.0"),"version":format!("{wrapper}.0.0{suffix}")}
            }}},
            "packages":{
                format!("a@{a}.0.0"):{"resolution":{"integrity":"sha512-a"}},
                format!("b@{b}.0.0"):{"resolution":{"integrity":"sha512-b"}},
                format!("wrapper@{wrapper}.0.0"):{"resolution":{"integrity":"sha512-wrapper"}},
                "lib@1.0.0":{"resolution":{"integrity":"sha512-lib"},"peerDependencies":{"a":"*"}}
            },
            "snapshots":{
                format!("a@{a}.0.0"):{}, format!("b@{b}.0.0"):{},
                format!("wrapper@{wrapper}.0.0{suffix}"):{"dependencies":{"lib":format!("1.0.0{suffix}")},"transitivePeerDependencies":if extended {vec!["a","b"]} else {vec!["a"]}},
                format!("lib@1.0.0{suffix}"):{"dependencies":{"a":format!("{a}.0.0")}}
            }
        });
        if extended {
            doc["packageExtensionsChecksum"] = json!("checksum-final");
            doc["packages"]["extra@1.0.0"] =
                json!({"resolution":{"integrity":"sha512-extra"},"peerDependencies":{"b":"*"}});
            doc["snapshots"][format!("extra@1.0.0(b@{b}.0.0)")] =
                json!({"dependencies":{"b":format!("{b}.0.0")}});
            doc["snapshots"][format!("lib@1.0.0{suffix}")]["dependencies"]["extra"] =
                json!(format!("1.0.0(b@{b}.0.0)"));
            doc["snapshots"][format!("lib@1.0.0{suffix}")]["transitivePeerDependencies"] =
                json!(["b"]);
        }
        Lockfile::parse(&doc.to_string()).unwrap()
    };
    let base = make(1, 1, 1, false);
    let ours = make(2, 2, 2, false);
    let theirs = make(1, 1, 1, true);
    let before = WorkspaceConfig::default();
    let after = cfg(&json!({"packageExtensions":{"lib@1":{"dependencies":{"extra":"1.0.0"}}}}));
    let manifests = BTreeMap::from([(
        ".".into(),
        json!({"dependencies":{"a":"2.0.0","b":"2.0.0","wrapper":"2.0.0"}}),
    )]);
    let patches = BTreeMap::new();
    let result = merge(
        &base,
        &ours,
        &theirs,
        Some(&MergeContext {
            registry: None,
            target: MergeTarget::Ours,
            manifests: &manifests,
            configurations: [&before, &before, &after],
            configuration: &after,
            patches: &patches,
        }),
    )
    .unwrap();
    result.validate().unwrap();
    let doc = result.project().unwrap();
    assert_eq!(
        doc["importers"]["."]["dependencies"]["wrapper"]["version"],
        "2.0.0(a@2.0.0)(b@2.0.0)"
    );
    assert_eq!(
        doc["snapshots"]["wrapper@2.0.0(a@2.0.0)(b@2.0.0)"]["dependencies"]["lib"],
        "1.0.0(a@2.0.0)(b@2.0.0)"
    );
    assert_eq!(
        doc["snapshots"]["lib@1.0.0(a@2.0.0)(b@2.0.0)"]["dependencies"]["extra"],
        "1.0.0(b@2.0.0)"
    );
    assert_eq!(
        doc["snapshots"]["extra@1.0.0(b@2.0.0)"]["dependencies"]["b"],
        "2.0.0"
    );
}

