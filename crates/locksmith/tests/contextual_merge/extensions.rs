#[test]
fn added_extensions_recompute_optional_usage_through_cycles_and_aliases() {
    for (group, direct) in [
        ("optionalDependencies", false),
        ("dependencies", false),
        ("optionalDependencies", true),
    ] {
        let before = WorkspaceConfig::default();
        let after = cfg(&json!({"packageExtensions":{"parent@1":{group:{"child":"1.0.0"}}}}));
        let source = Lockfile::parse(&json!({
            "lockfileVersion":"9.0","settings":{"autoInstallPeers":true,"excludeLinksFromLockfile":false},
            "importers":{".":{"dependencies":{"parent":{"specifier":"1.0.0","version":"1.0.0"},"shared":{"specifier":"1.0.0","version":"1.0.0"}}}},
            "packages":{"parent@1.0.0":{"resolution":{"integrity":"sha512-parent"}},"shared@1.0.0":{"resolution":{"integrity":"sha512-shared"}}},
            "snapshots":{"parent@1.0.0":{},"shared@1.0.0":{}}
        }).to_string()).unwrap();
        let optional = group == "dependencies";
        let donor = Lockfile::parse(&json!({
            "lockfileVersion":"9.0","settings":{"autoInstallPeers":true,"excludeLinksFromLockfile":false},
            "packageExtensionsChecksum":"sha256-extended",
            "importers":{".":{if optional {"optionalDependencies"} else {"dependencies"}:{"child":{"specifier":"1.0.0","version":"1.0.0"}}}},
            "packages":{"child@1.0.0":{"resolution":{"integrity":"sha512-child"}},"cycle@1.0.0":{"resolution":{"integrity":"sha512-cycle"}},"shared@1.0.0":{"resolution":{"integrity":"sha512-shared"}}},
            "snapshots":{"child@1.0.0":{"dependencies":{"cycle":"1.0.0","shared":"1.0.0"},"optional":optional},"cycle@1.0.0":{"dependencies":{"child":"1.0.0"},"optional":optional},"shared@1.0.0":{"optional":optional}}
        }).to_string()).unwrap();
        let mut manifest = json!({"dependencies":{"parent":"1.0.0","shared":"1.0.0"}});
        if direct {
            manifest["dependencies"]["alias"] = json!("npm:child@1.0.0");
        }
        let manifests = BTreeMap::from([(".".into(), manifest)]);
        let output = merge(
            &source,
            &source,
            &donor,
            Some(&MergeContext {
                registry: None,
                target: MergeTarget::Ours,
                manifests: &manifests,
                configurations: [&before, &before, &after],
                configuration: &after,
                patches: &BTreeMap::new(),
            }),
        )
        .unwrap();
        let snapshots = &output.project().unwrap()["snapshots"];
        for key in ["child@1.0.0", "cycle@1.0.0"] {
            assert_eq!(
                snapshots[key].get("optional"),
                (group == "optionalDependencies" && !direct).then_some(&json!(true))
            );
        }
        assert!(snapshots["shared@1.0.0"].get("optional").is_none());
        output.validate().unwrap();
    }
}

